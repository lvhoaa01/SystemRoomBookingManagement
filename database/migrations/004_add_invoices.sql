USE hotel_booking;

CREATE TABLE HoaDon (
  HoaDonID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  SoHoaDon VARCHAR(32) NOT NULL,
  DatChoID BIGINT UNSIGNED NOT NULL,
  ToChucDoiTacID BIGINT UNSIGNED NOT NULL,
  CoSoLuuTruID BIGINT UNSIGNED NOT NULL,
  KhachHangID BIGINT UNSIGNED NOT NULL,
  TrangThai VARCHAR(16) NOT NULL,
  TienTe CHAR(3) NOT NULL DEFAULT 'VND',
  TongTien DECIMAL(14,2) NOT NULL,
  DaThanhToan DECIMAL(14,2) NOT NULL,
  PhatHanhLuc DATETIME(6) NOT NULL,
  NguoiPhatHanhID BIGINT UNSIGNED NULL,
  SnapshotJSON JSON NOT NULL,
  TaoLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  UNIQUE KEY UQ_HoaDon_So (SoHoaDon),
  UNIQUE KEY UQ_HoaDon_DatCho (DatChoID),
  KEY IX_HoaDon_ToChucNgay (ToChucDoiTacID, PhatHanhLuc),
  KEY IX_HoaDon_KhachNgay (KhachHangID, PhatHanhLuc),
  CONSTRAINT FK_HoaDon_DatCho FOREIGN KEY (DatChoID) REFERENCES DatCho(DatChoID),
  CONSTRAINT FK_HoaDon_ToChuc FOREIGN KEY (ToChucDoiTacID) REFERENCES ToChucDoiTac(ToChucDoiTacID),
  CONSTRAINT FK_HoaDon_CoSo FOREIGN KEY (CoSoLuuTruID) REFERENCES CoSoLuuTru(CoSoLuuTruID),
  CONSTRAINT FK_HoaDon_Khach FOREIGN KEY (KhachHangID) REFERENCES NguoiDung(NguoiDungID),
  CONSTRAINT FK_HoaDon_NguoiPhatHanh FOREIGN KEY (NguoiPhatHanhID) REFERENCES NguoiDung(NguoiDungID),
  CONSTRAINT CK_HoaDon_TrangThai CHECK (TrangThai = 'ISSUED'),
  CONSTRAINT CK_HoaDon_Tien CHECK (
    TienTe = 'VND' AND TongTien >= 0 AND DaThanhToan = TongTien
  )
) ENGINE=InnoDB;

CREATE TABLE ChiTietHoaDon (
  ChiTietHoaDonID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  HoaDonID BIGINT UNSIGNED NOT NULL,
  ThuTu SMALLINT UNSIGNED NOT NULL,
  MoTa VARCHAR(500) NOT NULL,
  SoLuong SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  DonGia DECIMAL(14,2) NOT NULL,
  ThanhTien DECIMAL(14,2) NOT NULL,
  SnapshotJSON JSON NOT NULL,
  UNIQUE KEY UQ_ChiTietHoaDon_ThuTu (HoaDonID, ThuTu),
  CONSTRAINT FK_ChiTietHoaDon_HoaDon FOREIGN KEY (HoaDonID) REFERENCES HoaDon(HoaDonID),
  CONSTRAINT CK_ChiTietHoaDon_ThuTu CHECK (ThuTu > 0 AND SoLuong > 0),
  CONSTRAINT CK_ChiTietHoaDon_Tien CHECK (
    DonGia >= 0 AND ThanhTien >= 0 AND ThanhTien = DonGia * SoLuong
  )
) ENGINE=InnoDB;

USE hotel_booking;

CREATE TABLE KyDoiSoat (
  KyDoiSoatID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ToChucDoiTacID BIGINT UNSIGNED NOT NULL,
  CoSoLuuTruID BIGINT UNSIGNED NOT NULL,
  TuNgay DATE NOT NULL,
  DenNgay DATE NOT NULL,
  TrangThai VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
  TienTe CHAR(3) NOT NULL DEFAULT 'VND',
  SoDatCho INT UNSIGNED NOT NULL DEFAULT 0,
  DoanhThuGop DECIMAL(14,2) NOT NULL DEFAULT 0,
  ThuTrucTuyen DECIMAL(14,2) NOT NULL DEFAULT 0,
  ThuTaiCoSo DECIMAL(14,2) NOT NULL DEFAULT 0,
  DaHoan DECIMAL(14,2) NOT NULL DEFAULT 0,
  DoanhThuThuan DECIMAL(14,2) NOT NULL DEFAULT 0,
  NguoiTaoID BIGINT UNSIGNED NULL,
  TaoLuc DATETIME(6) NOT NULL,
  NguoiChotID BIGINT UNSIGNED NULL,
  ChotLuc DATETIME(6) NULL,
  CapNhatLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY UQ_KyDoiSoat_CoSoKy (CoSoLuuTruID, TuNgay, DenNgay),
  KEY IX_KyDoiSoat_ToChuc (ToChucDoiTacID, TrangThai, DenNgay),
  CONSTRAINT FK_KyDoiSoat_ToChuc FOREIGN KEY (ToChucDoiTacID) REFERENCES ToChucDoiTac(ToChucDoiTacID),
  CONSTRAINT FK_KyDoiSoat_CoSo FOREIGN KEY (CoSoLuuTruID) REFERENCES CoSoLuuTru(CoSoLuuTruID),
  CONSTRAINT FK_KyDoiSoat_NguoiTao FOREIGN KEY (NguoiTaoID) REFERENCES NguoiDung(NguoiDungID),
  CONSTRAINT FK_KyDoiSoat_NguoiChot FOREIGN KEY (NguoiChotID) REFERENCES NguoiDung(NguoiDungID),
  CONSTRAINT CK_KyDoiSoat_Ngay CHECK (TuNgay <= DenNgay),
  CONSTRAINT CK_KyDoiSoat_TrangThai CHECK (TrangThai IN ('DRAFT','FINALIZED')),
  CONSTRAINT CK_KyDoiSoat_Tien CHECK (
    TienTe='VND' AND SoDatCho>=0 AND DoanhThuGop>=0 AND ThuTrucTuyen>=0
    AND ThuTaiCoSo>=0 AND DaHoan>=0 AND DoanhThuThuan>=0
    AND DoanhThuGop=ThuTrucTuyen+ThuTaiCoSo
    AND DoanhThuThuan=DoanhThuGop-DaHoan
  ),
  CONSTRAINT CK_KyDoiSoat_Chot CHECK (
    (TrangThai='DRAFT' AND NguoiChotID IS NULL AND ChotLuc IS NULL) OR
    (TrangThai='FINALIZED' AND NguoiChotID IS NOT NULL AND ChotLuc IS NOT NULL)
  )
) ENGINE=InnoDB;

CREATE TABLE ChiTietDoiSoat (
  ChiTietDoiSoatID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  KyDoiSoatID BIGINT UNSIGNED NOT NULL,
  HoaDonID BIGINT UNSIGNED NOT NULL,
  MaDatCho VARCHAR(20) NOT NULL,
  SoHoaDon VARCHAR(32) NOT NULL,
  ThoiDiemThanhToan VARCHAR(20) NOT NULL,
  KenhThu VARCHAR(32) NOT NULL,
  TongTien DECIMAL(14,2) NOT NULL,
  DaHoan DECIMAL(14,2) NOT NULL DEFAULT 0,
  DoanhThuThuan DECIMAL(14,2) NOT NULL,
  PhatHanhLuc DATETIME(6) NOT NULL,
  SnapshotJSON JSON NOT NULL,
  UNIQUE KEY UQ_ChiTietDoiSoat_KyHoaDon (KyDoiSoatID, HoaDonID),
  KEY IX_ChiTietDoiSoat_HoaDon (HoaDonID),
  CONSTRAINT FK_ChiTietDoiSoat_Ky FOREIGN KEY (KyDoiSoatID) REFERENCES KyDoiSoat(KyDoiSoatID),
  CONSTRAINT FK_ChiTietDoiSoat_HoaDon FOREIGN KEY (HoaDonID) REFERENCES HoaDon(HoaDonID),
  CONSTRAINT CK_ChiTietDoiSoat_Timing CHECK (ThoiDiemThanhToan IN ('PAY_ONLINE','PAY_AT_PROPERTY')),
  CONSTRAINT CK_ChiTietDoiSoat_Kenh CHECK (KenhThu IN ('ONLINE','CASH','BANK_TRANSFER','CARD_AT_PROPERTY')),
  CONSTRAINT CK_ChiTietDoiSoat_Tien CHECK (
    TongTien>=0 AND DaHoan>=0 AND DoanhThuThuan>=0 AND DoanhThuThuan=TongTien-DaHoan
  )
) ENGINE=InnoDB;
